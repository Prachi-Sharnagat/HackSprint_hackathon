"use client";

import React from "react";
import { X, Maximize2, Minimize2, Sparkles } from "lucide-react";
import { VisualArtifact } from "@/hooks/useChat";
import { MindMapRenderer } from "../visuals/MindMapRenderer";
import { SlidePreview } from "../visuals/SlidePreview";

interface SlideOverWindowProps {
  isOpen: boolean;
  onClose: () => void;
  artifact: VisualArtifact | null;
}

export const SlideOverWindow: React.FC<SlideOverWindowProps> = ({
  isOpen,
  onClose,
  artifact,
}) => {
  const [isExpanded, setIsExpanded] = React.useState(false);

  if (!isOpen || !artifact) return null;

  return (
    <div
      className={`fixed top-0 right-0 h-full z-50 bg-slate-950/95 border-l border-slate-800 shadow-2xl flex flex-col transition-all duration-300 ease-in-out ${
        isExpanded ? "w-full md:w-[85vw]" : "w-full md:w-[540px] lg:w-[620px]"
      }`}
    >
      {/* Header */}
      <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800 bg-slate-900/60 backdrop-blur-md">
        <div className="flex items-center space-x-2.5">
          <div className="p-1.5 rounded-lg bg-indigo-500/10 border border-indigo-500/20 text-indigo-400">
            <Sparkles className="w-4 h-4" />
          </div>
          <div>
            <h3 className="text-sm font-semibold text-white tracking-tight">
              {artifact.title}
            </h3>
            <span className="text-[11px] text-slate-400 font-mono">
              Generated by {artifact.agentTag || "AI Agent"}
            </span>
          </div>
        </div>

        <div className="flex items-center space-x-2">
          <button
            onClick={() => setIsExpanded(!isExpanded)}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition hidden sm:inline-flex"
            title={isExpanded ? "Restore Size" : "Maximize Canvas"}
          >
            {isExpanded ? <Minimize2 className="w-4 h-4" /> : <Maximize2 className="w-4 h-4" />}
          </button>
          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition"
            title="Close Drawer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>
      </div>

      {/* Body Canvas */}
      <div className="flex-1 p-5 overflow-y-auto flex flex-col">
        {artifact.type === "mindmap" && (
          <MindMapRenderer mermaidCode={artifact.content} />
        )}

        {artifact.type === "slides" && (
          <SlidePreview jsonString={artifact.content} />
        )}

        {artifact.type === "markdown" && (
          <div className="p-6 bg-slate-900/60 rounded-xl border border-slate-800 text-slate-300 font-mono text-xs whitespace-pre-wrap">
            {artifact.content}
          </div>
        )}
      </div>
    </div>
  );
};
