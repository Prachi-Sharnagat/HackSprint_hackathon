class DecisionToolExecutor:
    """Executes the function calls generated by Gemini."""

    @staticmethod
    def execute_analyze_impact(decision_summary: str, scope: str, severity: str) -> Dict[str, Any]:
        """Calculates impact metrics, affected scopes, and risk factors."""
        risks = []
        if severity in ["high", "critical"]:
            risks.append("Potential deadline delay for sprint milestone")
            risks.append("Dependent services may require API versioning adjustments")
        else:
            risks.append("Minor coordination overhead across frontend and backend")

        return {
            "status": "success",
            "analysis": {
                "summary": f"Evaluated impact of '{decision_summary}' across {scope}.",
                "severity": severity,
                "scope": scope,
                "risks": risks,
                "mitigation": "Review proposed task updates and reassign blocked dependencies."
            }
        }

    @staticmethod
    def execute_get_related_tasks(
        room_tasks: List[Dict[str, Any]],
        keywords: List[str],
        include_dependencies: bool = True
    ) -> Dict[str, Any]:
        """Filters room tasks by matching keywords and includes blocked dependencies."""
        matched = []
        lower_keywords = [k.lower() for k in keywords]

        for t in room_tasks:
            text = f"{t.get('title', '')} {t.get('description', '')} {' '.join(t.get('tags', []))}".lower()
            if any(k in text for k in lower_keywords):
                matched.append(t)

        return {
            "status": "success",
            "matched_task_count": len(matched),
            "tasks": matched
        }

    @staticmethod
    def execute_propose_task_updates(proposals: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Validates and packages proposed updates for user approval."""
        validated_proposals = []
        for p in proposals:
            validated_proposals.append({
                "taskId": p.get("task_id"),
                "taskTitle": p.get("task_title", "Untitled Task"),
                "proposedStatus": p.get("proposed_status", "in_progress"),
                "proposedPriority": p.get("proposed_priority", "high"),
                "rationale": p.get("rationale", "Updated based on decision impact analysis"),
                "approvalStatus": "pending"
            })

        return {
            "status": "success",
            "proposal_count": len(validated_proposals),
            "proposals": validated_proposals
        }
